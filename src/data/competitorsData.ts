/** Admin-only competitive landscape. Never import from public pages. */

export type CompetitorKind =
    | 'meetup'
    | 'community'
    | 'accelerator'
    | 'venue_ecosystem'
    | 'identity_community'
    | 'other';

export type CompetitorOverlap =
    | 'direct' // same room: immigrant/international founders in Austin
    | 'adjacent' // Austin founders broadly; different primary audience
    | 'upstream' // venue / ecosystem host, not a peer meetup brand
    | 'national'; // immigrant-founder focus, weak/no Austin meetup surface

/** Research board operational status (active / dormant / unknown). */
export type CompetitorActivityStatus = 'active' | 'dormant' | 'unknown';

export interface Competitor {
    id: string; // kebab-case stable key
    name: string;
    kind: CompetitorKind;
    overlap: CompetitorOverlap;
    /** One-line what they are (public, verifiable) — from Research audience. */
    summary: string;
    /** City/region focus from Research geography. */
    geography: string;
    /** Homepage or primary listing URL when known. */
    url: string | null;
    /** Meetup / Luma / Eventbrite listing if different from url. */
    eventsUrl: string | null;
    /** Venue or host relationship from Research venue. */
    venueNote: string | null;
    /** Qualitative compare-on chips — no fake metrics. */
    compareOn: string[];
    /** Free-text notes; includes Research cadence, pricing, strengths/gaps. */
    notes: string;
    /** Research hygiene: URLs consulted. */
    sources: string[];
    lastReviewed: string; // ISO date, America/Chicago intent
    status: 'draft' | 'verified'; // seed starts as draft
    /** Research board status field (active/dormant/unknown). */
    activityStatus: CompetitorActivityStatus;
}

